// Package unicodedcp carries the Default_Ignorable_Code_Point property of
// Unicode 17.0.0. The Go unicode package has no such property, so its table is
// generated from the Unicode data file by go generate (gen/main.go), and a test
// requires the committed table to be that generation. The data file is Unicode's
// own, distributed under the Unicode License v3, whose text stands beside it in
// testdata/UNICODE-LICENSE.txt.
package unicodedcp

//go:generate go run ./gen

import (
	"bytes"
	"fmt"
	"github.com/polyspec/flowmark/packages/go/internal/ucd"
	"go/format"
	"io"
	"sort"
)

// UnicodeVersion is the version of the Unicode data that the table is generated from.
const UnicodeVersion = "17.0.0"

// Source is the public URL of the data file of UnicodeVersion.
const Source = "https://www.unicode.org/Public/" + UnicodeVersion + "/ucd/DerivedCoreProperties.txt"

// property is the name of the property that the table holds.
const property = "Default_Ignorable_Code_Point"

// Range is an inclusive range of code points.
type Range struct{ Lo, Hi rune }

// DefaultIgnorable reports whether r has the Default_Ignorable_Code_Point property.
func DefaultIgnorable(r rune) bool {
	i := sort.Search(len(defaultIgnorable), func(i int) bool { return defaultIgnorable[i].Hi >= r })
	return i < len(defaultIgnorable) && defaultIgnorable[i].Lo <= r
}

// Parse reads a DerivedCoreProperties file of UnicodeVersion and returns the
// ranges of Default_Ignorable_Code_Point in ascending order. The file must begin
// with its own version header; a line of another property is skipped. A range
// that is malformed, that is out of order or overlaps the one before, or that
// names no code point is refused, and so is a file with no range of the property.
func Parse(r io.Reader) ([]Range, error) {
	var ranges []Range
	err := ucd.ReadRanges(r, "DerivedCoreProperties", UnicodeVersion, func(line int, lo, hi rune, value string) error {
		if value != property {
			return nil
		}
		if len(ranges) > 0 && lo <= ranges[len(ranges)-1].Hi {
			return fmt.Errorf("line %d: the range %04X..%04X is out of order or overlaps the one before", line, lo, hi)
		}
		ranges = append(ranges, Range{Lo: lo, Hi: hi})
		return nil
	})
	if err != nil {
		return nil, err
	}
	if len(ranges) == 0 {
		return nil, fmt.Errorf("the file has no range of %s", property)
	}
	return ranges, nil
}

// dataFile is the data file in testdata/ that table.go is rendered from.
const dataFile = "testdata/DerivedCoreProperties-" + UnicodeVersion + ".txt"

// Table returns the Go source of table.go rendered from the data file in testdata/, read from the package directory:
// gen writes it, and a test requires the committed table to be it.
func Table() ([]byte, error) {
	ranges, err := ucd.ParseFile(dataFile, Parse)
	if err != nil {
		return nil, err
	}
	return Render(ranges)
}

// Render returns the Go source of table.go for ranges, in gofmt form.
func Render(ranges []Range) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate; DO NOT EDIT.\n")
	b.WriteString("// Source: " + Source + "\n")
	b.WriteString("// The " + property + " ranges of Unicode " + UnicodeVersion + " are the lines of\n")
	b.WriteString("// testdata/DerivedCoreProperties-" + UnicodeVersion + ".txt that name it.\n\n")
	b.WriteString("package unicodedcp\n\n")
	b.WriteString("// defaultIgnorable holds the ranges of " + property + " in ascending order.\n")
	b.WriteString("var defaultIgnorable = []Range{\n")
	for _, r := range ranges {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X},\n", r.Lo, r.Hi)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
